import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const FRONTEND_ROOT = path.resolve(__dirname, '..');
const NODE_MODULES_DIR = path.join(FRONTEND_ROOT, 'node_modules');
const VENDOR_TARGET_DIR = path.join(FRONTEND_ROOT, 'src', 'vendor');

export const VENDOR_BUNDLE_MAP = [
  {
    targetName: 'angular.min.js',
    candidates: [
      'angular/angular.min.js',
      'angular/angular.js'
    ]
  },
  {
    targetName: 'angular-ui-router.min.js',
    candidates: [
      '@uirouter/angularjs/release/angular-ui-router.min.js',
      '@uirouter/angularjs/release/angular-ui-router.js'
    ]
  },
  {
    targetName: 'chart.umd.js',
    candidates: [
      'chart.js/dist/chart.umd.js',
      'chart.js/dist/chart.umd.min.js'
    ]
  },
  {
    targetName: 'signalr.min.js',
    candidates: [
      '@microsoft/signalr/dist/browser/signalr.min.js',
      '@microsoft/signalr/dist/browser/signalr.js'
    ]
  }
];

export const FONT_ASSET_SPECS = [
  {
    packageName: '@fontsource/be-vietnam-pro',
    slug: 'be-vietnam-pro',
    weights: [400, 500, 600],
    subsets: ['vietnamese', 'latin']
  },
  {
    packageName: '@fontsource/space-grotesk',
    slug: 'space-grotesk',
    weights: [600, 700],
    subsets: ['vietnamese', 'latin']
  },
  {
    packageName: '@fontsource/jetbrains-mono',
    slug: 'jetbrains-mono',
    weights: [500, 600],
    subsets: ['vietnamese', 'latin']
  }
];

export const PHOSPHOR_WEIGHT_SPECS = [
  { weight: 'regular', fontFileBase: 'Phosphor' },
  { weight: 'fill', fontFileBase: 'Phosphor-Fill' },
  { weight: 'duotone', fontFileBase: 'Phosphor-Duotone' }
];

export function resolveVendorSourcePath(targetName) {
  const spec = VENDOR_BUNDLE_MAP.find((item) => item.targetName === targetName);
  if (!spec) {
    return null;
  }
  for (const relCandidate of spec.candidates) {
    const candidatePath = path.join(NODE_MODULES_DIR, relCandidate);
    if (fs.existsSync(candidatePath)) {
      return candidatePath;
    }
  }
  return null;
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function verifyCssAssetUrls(cssFilePath) {
  const cssText = fs.readFileSync(cssFilePath, 'utf8');
  const cssDir = path.dirname(cssFilePath);
  const urlMatches = [...cssText.matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g)];
  if (urlMatches.length === 0) {
    throw new Error(`[stage-vendor] Expected at least one url(...) declaration in ${path.relative(FRONTEND_ROOT, cssFilePath)}.`);
  }

  let verified = 0;
  for (const match of urlMatches) {
    const rawUrl = match[1].trim();
    if (/^(?:data:|https?:)/i.test(rawUrl)) {
      throw new Error(`[stage-vendor] Disallowed non-local font URL '${rawUrl}' in ${path.relative(FRONTEND_ROOT, cssFilePath)}.`);
    }
    const cleanRel = rawUrl.split(/[?#]/)[0];
    const resolvedTarget = path.resolve(cssDir, cleanRel);
    if (!fs.existsSync(resolvedTarget) || fs.statSync(resolvedTarget).size === 0) {
      throw new Error(
        `[stage-vendor] Broken CSS asset reference '${rawUrl}' in ${path.relative(FRONTEND_ROOT, cssFilePath)} -> ${path.relative(FRONTEND_ROOT, resolvedTarget)}`
      );
    }
    verified++;
  }
  return verified;
}

function stageSelfHostedFonts({ quiet }) {
  const fontsDir = path.join(VENDOR_TARGET_DIR, 'fonts');
  const fontsFilesDir = path.join(fontsDir, 'files');
  fs.mkdirSync(fontsFilesDir, { recursive: true });

  const combinedBlocks = [
    '/*',
    ' * Auto-generated by frontend/scripts/stage-vendor.mjs (Zero-CDN Self-Hosted Fonts)',
    ' * Families: Be Vietnam Pro (400/500/600), Space Grotesk (600/700), JetBrains Mono (500/600)',
    ' * Subsets: vietnamese + latin (with unicode-range preserved for diacritic integrity)',
    ' */'
  ];

  let stagedWoff2Count = 0;

  for (const spec of FONT_ASSET_SPECS) {
    const pkgDir = path.join(NODE_MODULES_DIR, ...spec.packageName.split('/'));
    if (!fs.existsSync(pkgDir)) {
      throw new Error(`[stage-vendor] Missing font package: ${spec.packageName}`);
    }

    for (const weight of spec.weights) {
      const weightCssPath = path.join(pkgDir, `${weight}.css`);
      if (!fs.existsSync(weightCssPath)) {
        throw new Error(`[stage-vendor] Missing font CSS file: ${path.relative(FRONTEND_ROOT, weightCssPath)}`);
      }
      const weightCss = fs.readFileSync(weightCssPath, 'utf8');

      for (const subset of spec.subsets) {
        const marker = `${spec.slug}-${subset}-${weight}-normal`;
        const blockRegex = new RegExp(
          `/\\*\\s*${escapeRegExp(marker)}\\s*\\*/\\s*@font-face\\s*\\{[\\s\\S]*?\\}`,
          'm'
        );
        const blockMatch = weightCss.match(blockRegex);
        if (!blockMatch) {
          throw new Error(
            `[stage-vendor] Could not locate @font-face block '${marker}' in ${path.relative(FRONTEND_ROOT, weightCssPath)}`
          );
        }

        const woff2Name = `${marker}.woff2`;
        const srcWoff2 = path.join(pkgDir, 'files', woff2Name);
        if (!fs.existsSync(srcWoff2)) {
          throw new Error(`[stage-vendor] Missing font binary: ${path.relative(FRONTEND_ROOT, srcWoff2)}`);
        }

        const destWoff2 = path.join(fontsFilesDir, woff2Name);
        fs.copyFileSync(srcWoff2, destWoff2);
        stagedWoff2Count++;

        const woff2OnlyBlock = blockMatch[0].replace(
          /src:\s*[^;]+;/,
          `src: url(./files/${woff2Name}) format('woff2');`
        );
        if (!woff2OnlyBlock.includes(`url(./files/${woff2Name})`)) {
          throw new Error(`[stage-vendor] Failed to rewrite src URL for '${marker}'.`);
        }

        combinedBlocks.push('', woff2OnlyBlock);
      }
    }
  }

  const combinedCssPath = path.join(fontsDir, 'fonts.css');
  fs.writeFileSync(combinedCssPath, `${combinedBlocks.join('\n')}\n`, 'utf8');
  const verifiedUrls = verifyCssAssetUrls(combinedCssPath);

  if (!quiet) {
    const cssKb = (fs.statSync(combinedCssPath).size / 1024).toFixed(1);
    console.log(
      `[stage-vendor] Staged fonts/fonts.css (${cssKb} KB) + ${stagedWoff2Count} .woff2 subset files (${verifiedUrls} URLs verified)`
    );
  }

  return { cssPath: combinedCssPath, woff2Count: stagedWoff2Count, verifiedUrls };
}

function stagePhosphorIcons({ quiet }) {
  const phosphorPkgRoot = path.join(NODE_MODULES_DIR, '@phosphor-icons', 'web', 'src');
  if (!fs.existsSync(phosphorPkgRoot)) {
    throw new Error('[stage-vendor] Missing icon package: @phosphor-icons/web');
  }

  const stagedWeights = [];
  let totalFontFiles = 0;
  let totalVerifiedUrls = 0;

  for (const spec of PHOSPHOR_WEIGHT_SPECS) {
    const srcWeightDir = path.join(phosphorPkgRoot, spec.weight);
    const destWeightDir = path.join(VENDOR_TARGET_DIR, 'phosphor', spec.weight);
    fs.mkdirSync(destWeightDir, { recursive: true });

    const woff2File = `${spec.fontFileBase}.woff2`;
    const ttfFile = `${spec.fontFileBase}.ttf`;
    const srcCssPath = path.join(srcWeightDir, 'style.css');

    for (const fileName of [woff2File, ttfFile]) {
      const srcFontPath = path.join(srcWeightDir, fileName);
      if (!fs.existsSync(srcFontPath)) {
        throw new Error(`[stage-vendor] Missing Phosphor font file: ${path.relative(FRONTEND_ROOT, srcFontPath)}`);
      }
      fs.copyFileSync(srcFontPath, path.join(destWeightDir, fileName));
      totalFontFiles++;
    }

    if (!fs.existsSync(srcCssPath)) {
      throw new Error(`[stage-vendor] Missing Phosphor stylesheet: ${path.relative(FRONTEND_ROOT, srcCssPath)}`);
    }

    const rawCss = fs.readFileSync(srcCssPath, 'utf8');
    const rewrittenCss = rawCss.replace(
      /(@font-face\s*\{[\s\S]*?)src:\s*[\s\S]*?;/,
      `$1src:\n    url("./${woff2File}") format("woff2"),\n    url("./${ttfFile}") format("truetype");`
    );
    if (rewrittenCss === rawCss || !rewrittenCss.includes(`url("./${woff2File}")`)) {
      throw new Error(`[stage-vendor] Failed to rewrite @font-face src in Phosphor ${spec.weight}/style.css.`);
    }

    const destCssPath = path.join(destWeightDir, 'style.css');
    fs.writeFileSync(destCssPath, rewrittenCss, 'utf8');
    const verifiedUrls = verifyCssAssetUrls(destCssPath);
    totalVerifiedUrls += verifiedUrls;
    stagedWeights.push(spec.weight);

    if (!quiet) {
      const cssKb = (fs.statSync(destCssPath).size / 1024).toFixed(1);
      console.log(
        `[stage-vendor] Staged phosphor/${spec.weight}/style.css (${cssKb} KB) + ${woff2File}, ${ttfFile} (${verifiedUrls} URLs verified)`
      );
    }
  }

  return { weights: stagedWeights, fontFiles: totalFontFiles, verifiedUrls: totalVerifiedUrls };
}

export function stageVendorAssets({ quiet = false } = {}) {
  if (!fs.existsSync(NODE_MODULES_DIR)) {
    if (!quiet) {
      console.warn('[stage-vendor] node_modules not found yet; skipping vendor copy.');
    }
    return { staged: 0, missing: VENDOR_BUNDLE_MAP.map((b) => b.targetName) };
  }

  fs.mkdirSync(VENDOR_TARGET_DIR, { recursive: true });

  let staged = 0;
  const missing = [];

  for (const bundle of VENDOR_BUNDLE_MAP) {
    const srcPath = resolveVendorSourcePath(bundle.targetName);
    if (!srcPath) {
      missing.push(bundle.targetName);
      continue;
    }
    const destPath = path.join(VENDOR_TARGET_DIR, bundle.targetName);
    fs.copyFileSync(srcPath, destPath);
    staged++;
    if (!quiet) {
      const sizeKb = (fs.statSync(destPath).size / 1024).toFixed(1);
      console.log(`[stage-vendor] Staged ${bundle.targetName} (${sizeKb} KB) <- ${path.relative(FRONTEND_ROOT, srcPath)}`);
    }
  }

  if (missing.length > 0) {
    throw new Error(`[stage-vendor] Missing browser vendor bundle(s): ${missing.join(', ')}`);
  }

  const fonts = stageSelfHostedFonts({ quiet });
  const phosphor = stagePhosphorIcons({ quiet });

  return {
    staged,
    fontsStaged: fonts.woff2Count,
    phosphorWeightsStaged: phosphor.weights.length,
    missing
  };
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === __filename;
if (isDirectRun) {
  stageVendorAssets();
}
